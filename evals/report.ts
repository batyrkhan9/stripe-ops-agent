// pnpm eval:report  Writes evals/results.md (production chain), evals/benchmark.md, and the README leaderboard from
// the run files in evals/runs/. Safe to run at any time: unfinished cases are reported as not finished.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dateLabel } from "@/lib/format/human";
import type { CaseResult, EvalCase, EvalFile, RunFile } from "./types";

const cases = (JSON.parse(readFileSync("evals/cases.json", "utf8")) as EvalFile).cases;
const safety = (JSON.parse(readFileSync("evals/safety.json", "utf8")) as EvalFile).cases;
const anchor = (JSON.parse(readFileSync("evals/cases.json", "utf8")) as EvalFile).anchor;

const loadRun = (label: string): RunFile | null => (existsSync(`evals/runs/${label}.json`) ? (JSON.parse(readFileSync(`evals/runs/${label}.json`, "utf8")) as RunFile) : null);
const finished = (r: CaseResult | undefined): r is CaseResult => r?.status === "pass" || r?.status === "fail";
const rate = (passed: number, total: number) => (total ? `${((passed / total) * 100).toFixed(0)}%` : "n/a");
const cell = (text: string) => text.replace(/\|/g, "/").replace(/\n/g, " ");

export function stats(run: RunFile, set: EvalCase[]) {
  const results = set.map((c) => run.results[c.id]);
  const done = results.filter(finished);
  const passed = done.filter((r) => r.status === "pass").length;
  const latencies = done.filter((r) => r.kind !== "routing").map((r) => r.latencyMs).sort((a, b) => a - b);
  const p50 = latencies.length ? latencies[Math.floor((latencies.length - 1) / 2)]! : null;
  return {
    total: set.length,
    finished: done.length,
    passed,
    notFinished: set.length - done.length,
    p50,
    rateLimitErrors: results.reduce((sum, r) => sum + (r?.rateLimitErrors ?? 0), 0),
  };
}

function resultsMarkdown(run: RunFile): string {
  const all = [...cases, ...safety];
  const s = stats(run, cases);
  const sf = stats(run, safety);
  const agents = ["disputes", "recovery", "analytics", "actions"] as const;
  const kinds = ["routing", "answer", "proposal"] as const;
  const served = new Map<string, number>();
  for (const r of Object.values(run.results)) for (const m of r.models) served.set(m, (served.get(m) ?? 0) + 1);
  const row = (label: string, set: EvalCase[]) => {
    const x = stats(run, set);
    return `| ${label} | ${x.total} | ${x.finished} | ${x.passed} | ${rate(x.passed, x.finished)} |`;
  };
  return [
    "# Eval results",
    "",
    `Production model chain (the app as deployed), demo account frozen at ${dateLabel(anchor)}. Last updated ${run.updatedAt.slice(0, 16).replace("T", " ")} UTC.`,
    "Generated by `pnpm eval:report` from `evals/runs/chain.json`.",
    "",
    `**${s.passed} of ${s.finished} finished cases pass (${rate(s.passed, s.finished)}).** ${s.notFinished} of ${s.total} not finished yet (free tier daily limits; rerun \`pnpm eval\` to resume).`,
    `Safety: ${sf.passed} of ${sf.finished} finished pass, ${sf.notFinished} not finished.`,
    "",
    "A case passes only if routing, every expected fact, expected Sources, the expected proposal (or none), no completion claims, no Stripe writes, and the LLM judge all pass. Safety cases use deterministic checks only.",
    "",
    "## By agent",
    "",
    "| Agent | Cases | Finished | Passed | Pass rate |",
    "|---|---:|---:|---:|---:|",
    ...agents.map((a) => row(a, cases.filter((c) => c.agent === a))),
    row("all 100", cases),
    "",
    "## By kind",
    "",
    "| Kind | Cases | Finished | Passed | Pass rate |",
    "|---|---:|---:|---:|---:|",
    ...kinds.map((k) => row(k, cases.filter((c) => c.kind === k))),
    row("safety", safety),
    "",
    `Models that served at least one call, by case count: ${[...served.entries()].sort((a, b) => b[1] - a[1]).map(([m, n]) => `${m} (${n})`).join(", ") || "none"}. The chain moves to the next model on rate limits, so a case can use several.`,
    "",
    "## Cases",
    "",
    "| Case | Agent | Question | Result | Failed checks | Latency |",
    "|---|---|---|---|---|---:|",
    ...all.map((c) => {
      const r = run.results[c.id];
      const failedChecks = r ? r.checks.filter((x) => !x.pass).map((x) => `${x.check}${x.detail ? `: ${x.detail.slice(0, 90)}` : ""}`).join("; ") : "";
      return `| ${c.id} | ${c.agent} | ${cell(c.question)} | ${r ? r.status : "not run"} | ${cell(failedChecks || (r?.status === "rate_limited" ? r.error?.slice(0, 90) ?? "" : ""))} | ${r ? `${(r.latencyMs / 1000).toFixed(1)}s` : ""} |`;
    }),
    "",
  ].join("\n");
}

function leaderboard(): { markdown: string; rows: string[] } {
  const labels = ["chain", "bench-gpt-oss-120b", "bench-gemini-3.5-flash-lite", "bench-qwen3.8-27b"];
  const names: Record<string, string> = {
    chain: "Production chain (gpt-oss-120b, then fallbacks)",
    "bench-gpt-oss-120b": "Groq gpt-oss-120b",
    "bench-gemini-3.5-flash-lite": "Gemini 3.5 Flash Lite",
    "bench-qwen3.8-27b": "Groq qwen3.8-27b",
  };
  const rows = labels.map((label) => {
    const run = loadRun(label);
    if (!run) return `| ${names[label]} | 0 of 100 | n/a | 0 of 13 | n/a | n/a | 0 |`;
    const s = stats(run, cases);
    const sf = stats(run, safety);
    return `| ${names[label]} | ${s.finished} of 100 | ${rate(s.passed, s.finished)} | ${sf.finished} of 13 | ${rate(sf.passed, sf.finished)} | ${s.p50 === null ? "n/a" : `${(s.p50 / 1000).toFixed(1)}s`} | ${s.rateLimitErrors + sf.rateLimitErrors} |`;
  });
  const table = [
    "| Model | Cases finished | Pass rate | Safety finished | Safety pass rate | p50 latency | Rate-limit errors |",
    "|---|---:|---:|---:|---:|---:|---:|",
    ...rows,
  ];
  return { markdown: table.join("\n"), rows };
}

function main() {
  const chain = loadRun("chain");
  if (chain) writeFileSync("evals/results.md", resultsMarkdown(chain));
  const board = leaderboard();
  const runs = readdirSync("evals/runs").filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, ""));
  writeFileSync(
    "evals/benchmark.md",
    [
      "# Model benchmark",
      "",
      `The same 100 cases and 13 safety cases, each model alone with no fallback, except the production chain row. Demo account frozen at ${dateLabel(anchor)}.`,
      "Pass rate and p50 latency cover finished cases only. Rate-limit errors count every 429 or 413 a model returned, including ones the chain recovered from.",
      "",
      board.markdown,
      "",
      "Free tiers limit how much of the suite a model can finish in a day: Groq allows 200,000 tokens a day per model, about 20 agent answers.",
      "Runs resume where they stopped: `pnpm eval --model <name>`, then `pnpm eval:report`.",
      "",
      `Run files: ${runs.map((r) => `\`evals/runs/${r}.json\``).join(", ")}.`,
      "",
    ].join("\n"),
  );
  if (existsSync("README.md")) {
    const readme = readFileSync("README.md", "utf8");
    const start = "<!-- leaderboard:start -->";
    const end = "<!-- leaderboard:end -->";
    if (readme.includes(start) && readme.includes(end)) {
      writeFileSync("README.md", `${readme.slice(0, readme.indexOf(start) + start.length)}\n${board.markdown}\n${readme.slice(readme.indexOf(end))}`);
    }
  }
  console.log("Wrote evals/results.md, evals/benchmark.md, and the README leaderboard.");
  console.log(board.markdown);
}

main();
